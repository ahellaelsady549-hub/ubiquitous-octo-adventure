function DuasPage() {
  const [active, setActive] = useState("all");
  const [q, setQ] = useState("");

  const list = useMemo(() => {
    const term = normalizeArabic(q);
    return sections
      .filter((s) => active === "all" || s.id === active)
      .map((s) => ({ ...s, items: term ? s.items.filter((d) => normalizeArabic(d.text).includes(term)) : s.items }))
      .filter((s) => s.items.length);
  }, [active, q]);

  return (
    <div className="mx-auto max-w-3xl px-4 py-8">
      <h1 className="text-3xl font-bold gold-gradient-text">الأدعية</h1>
      <div className="relative mt-5">
        <Search className="absolute right-3 top-1/2 h-4 w-4 -translate-y-1/2 text-muted-foreground" />
        <input
          value={q}
          onChange={(e) => setQ(e.target.value)}
          placeholder="ابحث في الأدعية..."
          className="w-full rounded-xl border border-border bg-card py-3 pl-3 pr-10 text-sm"
        />
      </div>
      <div className="mt-4 flex flex-wrap gap-2">
        {[{ id: "all", title: "الكل" }, ...sections].map((s) => (
          <button
            key={s.id}
            onClick={() => setActive(s.id)}
            className={`rounded-full border px-4 py-1.5 text-sm ${active === s.id ? "border-gold bg-secondary text-gold" : "border-border bg-card"}`}
          >
            {s.title}
          </button>
        ))}
      </div>
      {list.length === 0 && <p className="mt-10 text-center text-sm text-muted-foreground">لا توجد نتائج</p>}
      {list.map((s) => (
        <section key={s.id} className="mt-8">
          <h2 className="text-xl font-bold text-gold">{s.title}</h2>
          <div className="mt-3 space-y-3">
            {s.items.map((d, i) => (
              <article key={i} className="surface animate-fade-up p-5">
                <p className="font-display text-lg leading-9">{d.text}</p>
                <div className="mt-3 flex items-center justify-between text-xs text-muted-foreground">
                  <span>{d.source}</span>
                  <button
                    onClick={() => { void navigator.clipboard.writeText(d.text); toast.success("تم النسخ"); }}
                    className="inline-flex items-center gap-1 hover:text-gold"
                  >
                    <Copy className="h-3.5 w-3.5" /> نسخ
                  </button>
                </div>
              </article>
            ))}
          </div>
        </section>
      ))}
    </div>
  );
}
